/** 表示期間内のお知らせ（新しい順） */
export function getActiveReleaseNotes(now = new Date()) {
  const limit = SHOW_DAYS * 24 * 60 * 60 * 1000;
  return RELEASE_NOTES.filter((n) => {
    const d = new Date(`${n.date}T00:00:00+09:00`);
    return !Number.isNaN(d.getTime()) && now.getTime() - d.getTime() <= limit;
  });
}
